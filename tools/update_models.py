#!/usr/bin/env python3
"""Refresh model information from models.dev (run weekly by .github/workflows/models.yml).

- skills/llm-roundtable/scripts/opencode-models.json: free OpenCode models (id, name, family, release date,
  status). The script falls back to it when models.dev cannot be reached, and it shows which model the opt-in
  opencode seat picks.
- docs/model-watch.md: the model each seat runs, and newer models of the same family that models.dev lists.
  Fixed seats are never bumped automatically: a new model has to pass a real CLI call first (AGENTS.md).

Both files are stable (no timestamps), so the workflow opens a PR only when something changed.
Usage: python3 tools/update_models.py [--api models.json] [--check]
"""
import argparse
import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCRIPTS = ROOT / "skills/llm-roundtable/scripts"
sys.path.insert(0, str(SCRIPTS))
import roundtable  # noqa: E402

SNAPSHOT = SCRIPTS / "opencode-models.json"
WATCH = ROOT / "docs/model-watch.md"
PROVIDER = {"claude": "anthropic", "codex": "openai", "grok": "xai", "agy": "google"}
# CLI-only suffixes (agy's effort levels) that models.dev does not list
CLI_SUFFIX = re.compile(r"-(minimal|low|medium|high|xhigh)$")
# same family on models.dev, but not a model a seat can sit with
NOT_A_SEAT = re.compile(r"image|video|audio|tts|embed|latest|preview|realtime|transcribe", re.I)


def fetch(api):
    if api:
        return json.loads(Path(api).read_text(encoding="utf-8"))
    req = urllib.request.Request(roundtable.MODELS_DEV, headers={"User-Agent": "llm-roundtable-ci (+https://github.com/dinhkarate/llm-roundtable)"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.load(r)


def snapshot(api):
    keep = ("name", "family", "release_date", "status", "cost")
    models = {}
    for mid, m in sorted(api.get("opencode", {}).get("models", {}).items()):
        if "free" in mid or (m.get("cost") or {}).get("input") == 0:
            models[mid] = {k: m[k] for k in keep if m.get(k) is not None}
    return {"source": roundtable.MODELS_DEV, "models": models}


def newer_in_family(api, adapter, model):
    """(models.dev entry for `model`, newer text models of the same provider and family, newest first)."""
    models = api.get(PROVIDER.get(adapter, ""), {}).get("models", {})
    cur = models.get(model) or models.get(CLI_SUFFIX.sub("", model))
    if not cur or not cur.get("family"):
        return cur, []
    out = []
    for mid, m in models.items():
        if m.get("family") != cur["family"] or NOT_A_SEAT.search(mid) or m.get("status") == "deprecated":
            continue
        if (m.get("modalities") or {}).get("output", ["text"]) != ["text"]:
            continue
        if (m.get("release_date") or "") > (cur.get("release_date") or ""):
            out.append((m["release_date"], mid))
    return cur, [mid for _, mid in sorted(out, reverse=True)]


def watch(api, cfg, snap):
    lines = ["# Model watch", "",
             "Generated by `tools/update_models.py` from [models.dev](https://models.dev) (weekly CI). Fixed seats are",
             "only bumped by hand, after a real CLI call (`roundtable.py doctor --probe`). Edit `seats.json`, not this file.",
             "", "| Seat | Runs | Released | Newer on models.dev |", "|---|---|---|---|"]
    for s in cfg["seats"]:
        if s.get("homogeneous"):
            continue
        if isinstance(s["models"], str):
            free = ["opencode/" + mid for mid, m in snap["models"].items() if m.get("status") != "deprecated"]
            prefer = s.get("prefer") or []
            ranked = roundtable.rank_free_models(free, snap["models"], s.get("exclude", ""),
                                                 [prefer] if isinstance(prefer, str) else prefer)
            pick = ranked[0] if ranked else "none"
            rel = snap["models"].get(pick.split("/", 1)[-1], {}).get("release_date", "?")
            note = "auto: newest free model%s; fallback %s" % (
                " matching " + ", ".join(prefer if isinstance(prefer, list) else [prefer]) if prefer else "",
                ranked[1] if len(ranked) > 1 else "none")
            lines.append("| %s | `%s` | %s | %s |" % (s["id"], pick, rel, note))
            continue
        model = s["models"][0]
        cur, newer = newer_in_family(api, s["adapter"], model)
        rel = (cur or {}).get("release_date", "not on models.dev")
        lines.append("| %s | `%s` | %s | %s |" % (s["id"], model, rel, ", ".join("`%s`" % m for m in newer) or "none"))
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--api", help="read models.dev api.json from this file instead of the network")
    ap.add_argument("--check", action="store_true", help="exit 1 if a file would change, write nothing")
    args = ap.parse_args()
    api = fetch(args.api)
    if not api.get("opencode", {}).get("models"):
        raise SystemExit("models.dev answer has no opencode models; refusing to overwrite the snapshot")
    snap = snapshot(api)
    cfg = json.loads((SCRIPTS / "seats.json").read_text(encoding="utf-8"))
    out = {SNAPSHOT: json.dumps(snap, indent=1, sort_keys=True) + "\n", WATCH: watch(api, cfg, snap)}
    changed = [p for p, text in out.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    for p in changed:
        print("changed:", p.relative_to(ROOT))
        if not args.check:
            p.write_text(out[p], encoding="utf-8")
    if args.check and changed:
        sys.exit(1)


if __name__ == "__main__":
    main()
